// Empacotado no init a partir da arte. Sprite com pixel trocado só se descobre
// olhando, então a fonte da verdade é o desenho, não o hex.
var sprites [5]display.Sprite

func init() {
	for i, arte := range [...]string{arteOvo, arteFilhote, arteJovem, arteAdulto, arteVeterano} {
		sprites[i] = empacota(arte, larguraSprite, alturaSprite)
	}
}

// A arte tem TRÊS tons, não dois:
//
//	'#'  sólido
//	':'  dither em xadrez, que o olho lê como cinza
//	'.'  vazio
//
// Um bit por pixel dá dois tons; o dither dá um terceiro de graça, e é o que
// separa pixel art de silhueta preenchida. Sem ele o bicho é uma mancha preta
// com buracos, que foi exatamente o problema da primeira versão.
//
// O xadrez usa (x+y)%2 e não um padrão por sprite: assim dois sprites
// encostados não formam faixa, e o bicho não "vibra" quando anda pela tela.
func empacota(arte string, w, h int16) display.Sprite {
	stride := (w + 7) / 8
	bits := make([]byte, int(stride)*int(h))
	linha, col := int16(0), int16(0)

	acende := func() {
		if linha < h && col < w {
			bits[int(linha)*int(stride)+int(col/8)] |= 0x80 >> (col % 8)
		}
	}

	for i := 0; i < len(arte); i++ {
		switch arte[i] {
		case '\n', '\r':
			if col > 0 {
				linha++
			}
			col = 0
			continue
		case '#':
			acende()
		case ':':
			if (col+linha)%2 == 0 {
				acende()
			}
		}
		col++
	}
	return display.Sprite{W: w, H: h, Stride: stride, Bits: bits}
}

// SpriteDoEstagio devolve a arte do estágio. Estágio fora da faixa cai no ovo
// em vez de dar pânico: no device, pânico é tela morta sem pista nenhuma.
func SpriteDoEstagio(s sim.Stage) display.Sprite {
	if int(s) >= len(sprites) {
		return sprites[0]
	}
	return sprites[s]
}
